/**
 * Writes packages/ui/docs/props.generated.ts: every documented interface's props, read from the
 * component sources and their JSDoc. Run it after changing a component's props; a test fails
 * while the checked-in file is out of date.
 *
 *   node scripts/generate-props.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { spec } from "../packages/ui/docs/spec.ts";
import { extractProps, typeAliases, type PropDoc } from "../packages/ui/docs/props.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
export const OUTPUT = join(root, "packages/ui/docs/props.generated.ts");

/** Every `.tsx` and `.ts` file under packages/ui/src, for type aliases a prop might use. */
function sources(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return sources(path);
    return /\.tsx?$/.test(entry.name) && !entry.name.endsWith(".test.ts") ? [path] : [];
  });
}

export function generate(): string {
  const aliases = Object.assign({}, ...sources(join(root, "packages/ui/src")).map((f) => typeAliases(readFileSync(f, "utf8"))));
  const props: Record<string, PropDoc[]> = {};
  for (const { parts } of Object.values(spec)) {
    for (const part of parts) {
      props[part.interface] ??= extractProps(readFileSync(join(root, part.source), "utf8"), part.interface, aliases);
    }
  }
  return [
    "// Generated by scripts/generate-props.ts from the component sources. Don't edit by hand.",
    'import type { PropDoc } from "./props.ts";',
    "",
    `export const PROPS: Record<string, PropDoc[]> = ${JSON.stringify(props, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(OUTPUT, generate());
  console.log(`Wrote ${OUTPUT}`);
}
